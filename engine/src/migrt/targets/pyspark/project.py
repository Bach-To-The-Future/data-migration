"""The delivered project (spec section 6, "The delivered project"): the files a client and the final validator
need to run the generated code, laid out as `converted/<Database>/<schema>/<kind>/<Name>.py` (a query batch under
`converted/<Database>/batches/`), one artefact per file, names under the recorded adjustment rules, with a
package in every folder so that a callee is imported as a module.

Carried with the code:
- `manifest.json`: one entry point per artefact, saying how to invoke it and read its results;
- `settings.json`: the semantic settings, fixed and fingerprinted because they are part of what was verified; the
  runtime identity values; and the named settings that stand for marked secrets, to be filled in at deployment,
  which generated code reads through session state (`ss.setting(name)`);
- `representation-rules.md`: the type mapping's representation rules;
- `README.md`: what the files are.

Not carried yet, with the ticket that takes it: the vendored support library, its licence, the definition of the
state table (`migrt_spark.state_table_ddl`) and the commands that ship with it (issue #49).

Everything here is deterministic: no timestamps, sorted keys, the same inputs give the same bytes.
"""
from __future__ import annotations

import dataclasses
import hashlib
import json
import pathlib

from ...core.ir import Artefact
from . import types
from .generator import PROJECT_PACKAGE, GeneratedFile

MANIFEST_FORMAT = "migrt-manifest/1"
SETTINGS_FORMAT = "migrt-settings/1"
GENERATED = "generated, not reconciled"
WITH_MANUAL_WORK = "generated with manual work, not reconciled"
MANUAL_WORK = "manual work"
README = """# Delivered project

Generated by migrt. Nothing here counts as converted until it is reconciled and has passed final validation: the manifest
says the status of each entry point.

- `converted/`: the generated code, one artefact per file. A callee is imported as a module.
- `manifest.json`: one entry point per artefact, how to invoke it, and how to read its results.
- `settings.json`: the settings session state reads at startup. Fill in each secret before running.
- `representation-rules.md`: how each type is held in Spark and what the write wrapper or a helper reproduces.

Every function takes session state `ss` as its first argument. A function that is manual work raises when
called, and says which parts are.
"""


@dataclasses.dataclass(frozen=True)
class Unit:
    """One generated artefact."""
    artefact: Artefact
    generated: GeneratedFile


def status(generated: GeneratedFile) -> str:
    if generated.fails_when_called:
        return MANUAL_WORK
    return WITH_MANUAL_WORK if generated.manual_items else GENERATED


def _result(generated: GeneratedFile) -> str:
    if generated.fails_when_called:
        return "raises RuntimeError when called: it is manual work, and the error says which parts"
    if generated.result == "dataframe":
        return ("a DataFrame with the columns listed in `columns`, lazily evaluated: collect it, or hand it to a "
                "write wrapper")
    if generated.result == "column":
        return "a Column expression: use it in select, filter or withColumn"
    return "nothing"


def entry_point(unit: Unit) -> dict:
    a, g = unit.artefact, unit.generated
    module = g.relative_path.removesuffix(".py").replace("/", ".")
    entry: dict = {
        "artefact": a.identity, "type": a.artefact_type, "status": status(g),
        "module": module, "file": g.relative_path, "functions": g.functions,
        "signature": g.signature,
        "call": "BATCHES (call each in order with ss)" if a.artefact_type == "query_batch"
        else f"{g.functions[0]}({g.signature})",
        "parameters": g.parameters, "result": _result(g),
        "manual_items": len(g.manual_items), "depends_on": sorted(a.dependencies),
        "settings_read": g.settings_used,
    }
    if g.columns is not None and not g.fails_when_called:
        entry["columns"] = g.columns
    return entry


def manifest(snapshot_id: str, tool_version: str, units: list[Unit]) -> dict:
    return {"format": MANIFEST_FORMAT, "snapshot": snapshot_id, "tool_version": tool_version,
            "entry_points": sorted((entry_point(u) for u in units), key=lambda e: e["artefact"])}


def settings(engagement: str, snapshot_id: str, semantic: dict, runtime_identity: dict[str, str],
             units: list[Unit]) -> dict:
    """`semantic` is what the catalog snapshot and the engagement say, each with its origin; `runtime_identity`
    names each value that depends on the machine and what the Databricks runtime maps it to by default (spec
    section 7), overridable at deployment."""
    secrets: dict[str, dict] = {}
    for unit in units:
        for name in unit.artefact.secret_settings:
            entry = secrets.setdefault(name, {"value": None, "required_by": [], "read_by_code": False})
            entry["required_by"] = sorted({*entry["required_by"], unit.artefact.identity})
            entry["read_by_code"] = entry["read_by_code"] or name in unit.generated.settings_used
    fingerprint = hashlib.sha256(json.dumps(semantic, sort_keys=True).encode("utf-8")).hexdigest()
    return {"format": SETTINGS_FORMAT, "engagement": engagement, "snapshot": snapshot_id, "semantic": semantic,
            "fingerprint": fingerprint,
            "runtime_identity": {k: {"default": v, "override": None} for k, v in sorted(runtime_identity.items())},
            "secrets": dict(sorted(secrets.items()))}


def _dumps(data: dict) -> str:
    return json.dumps(data, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def write(out_dir: pathlib.Path, *, engagement: str, snapshot_id: str, tool_version: str, semantic: dict,
          runtime_identity: dict[str, str], units: list[Unit]) -> list[str]:
    """Write the project under `out_dir`; returns the paths written, relative to it and sorted."""
    files: dict[str, str] = {u.generated.relative_path: u.generated.text for u in units}
    for path in list(files):
        folder = pathlib.PurePosixPath(path).parent
        for parent in [folder, *folder.parents]:
            if str(parent) not in (".", ""):
                files.setdefault(f"{parent}/__init__.py", "")
    outside = [p for p in files if p.split("/")[0] != PROJECT_PACKAGE]
    if outside:
        raise ValueError(f"generated files outside the {PROJECT_PACKAGE} package: {outside}")
    files["manifest.json"] = _dumps(manifest(snapshot_id, tool_version, units))
    files["settings.json"] = _dumps(settings(engagement, snapshot_id, semantic, runtime_identity, units))
    files["representation-rules.md"] = types.representation_rules_markdown()
    files["README.md"] = README
    for relative, text in files.items():
        target = out_dir / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")
    return sorted(files)
