"""Run the inferred-difference cases on SQL Server and on local Spark.

Runs inside the sandbox tools container; `python corpus/build.py --differences`
is the entry point. Writes corpus/differences/results.json and results.md.
"""
import datetime
import decimal
import json
import pathlib
import sys

import db

CORPUS = pathlib.Path(__file__).resolve().parents[1]
OUT = CORPUS / "differences"
SCRATCH_DB = "DifferenceScratch"

sys.path.insert(0, str(OUT))
import cases  # noqa: E402


def plain(value):
    """Make an observation JSON-serialisable without losing what it was."""
    if isinstance(value, dict):
        return {k: plain(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [plain(v) for v in value]
    if isinstance(value, decimal.Decimal):
        return str(value)
    if isinstance(value, (datetime.date, datetime.datetime)):
        return value.isoformat()
    if isinstance(value, bytes):
        return value.hex()
    return value


def attempt(fn):
    """Run fn; report its value or the first line of its error."""
    try:
        return {"ok": fn()}
    except Exception as exc:  # the point is to observe any failure
        # A Java error's first line only names the call; the cause is on the second.
        lines = [line.strip(" :") for line in str(exc).splitlines() if line.strip(" :")]
        return {"error": f"{type(exc).__name__}: {' | '.join(lines[:2])}"[:400]}


def observe_tsql(case):
    batches = case["tsql"] if isinstance(case["tsql"], list) else [case["tsql"]]
    observed = []
    for batch in batches:
        sets, messages = db.observe(SCRATCH_DB, batch)
        observed.append({
            "sets": [rows for _columns, rows in sets],
            "errors": [text for severity, text in messages if severity > 10],
        })
    return observed if case.get("all_batches") else observed[-1]


def start_spark():
    from delta import configure_spark_with_delta_pip
    from pyspark.sql import SparkSession

    builder = (
        SparkSession.builder.master("local[2]")
        .appName("differences")
        .config("spark.sql.extensions", "io.delta.sql.DeltaSparkSessionExtension")
        .config("spark.sql.catalog.spark_catalog", "org.apache.spark.sql.delta.catalog.DeltaCatalog")
        .config("spark.sql.warehouse.dir", "/tmp/differences-warehouse")
        .config("spark.sql.session.timeZone", "UTC")
        .config("spark.sql.shuffle.partitions", "1")
        .config("spark.ui.enabled", "false")
        .config("spark.ui.showConsoleProgress", "false")
    )
    spark = configure_spark_with_delta_pip(builder).getOrCreate()
    # The cases provoke errors on purpose; they are recorded in the results, not logged.
    spark.sparkContext.setLogLevel("OFF")
    return spark


def run_case(case, spark):
    result = {"id": case["id"], "title": case["title"], "claim": case["claim"]}
    try:
        tsql = observe_tsql(case)
        spark_seen = case["spark"](spark, attempt)
        verdict, note = case["judge"](tsql, spark_seen)
        result.update(tsql=plain(tsql), spark=plain(spark_seen), verdict=verdict, note=note)
    except Exception as exc:
        result.update(verdict="not run", note=f"{type(exc).__name__}: {exc}"[:400])
    print(f"  {case['id']:<18} {result['verdict']:<17} {case['title']}", flush=True)
    return result


def environment(spark):
    conn = db.connect(SCRATCH_DB)
    version = db.query(conn, "SELECT CAST(SERVERPROPERTY('ProductVersion') AS varchar(30)), "
                             "CAST(SERVERPROPERTY('ProductUpdateLevel') AS varchar(30)), "
                             "CAST(SERVERPROPERTY('Edition') AS varchar(60)), "
                             "CAST(DATABASEPROPERTYEX(DB_NAME(), 'Collation') AS varchar(60))")[0]
    conn.close()
    import delta
    import importlib.metadata
    return {
        "sql_server": {"version": version[0], "update_level": version[1], "edition": version[2],
                       "database_collation": version[3]},
        "spark": {"version": spark.version,
                  "delta": importlib.metadata.version("delta-spark"),
                  "ansi_enabled": spark.conf.get("spark.sql.ansi.enabled"),
                  "mode": "local, open-source Spark with Delta Lake; not a Databricks Runtime"},
    }


def write_markdown(env, results, extras):
    def cell(text):
        return str(text).replace("|", "\\|").replace("\n", " ")

    counts = {}
    for r in results:
        counts[r["verdict"]] = counts.get(r["verdict"], 0) + 1
    lines = [
        "# Inferred differences, tested",
        "",
        "Generated by `python corpus/build.py --differences`. Do not edit by hand.",
        "",
        "The research in `docs/research/tsql-spark-silent-differences.md` marks 14 differences as inferred: "
        "documented on one side only. Each was run on both sides here. The cases are in `cases.py`; "
        "the raw observations are in `results.json`.",
        "",
        f"- SQL Server {env['sql_server']['version']} ({env['sql_server']['update_level']}), "
        f"{env['sql_server']['edition']}, database collation `{env['sql_server']['database_collation']}`",
        f"- Spark {env['spark']['version']} with Delta {env['spark']['delta']}, ANSI mode "
        f"{'on' if env['spark']['ansi_enabled'] == 'true' else 'off'}. {env['spark']['mode']}.",
        "",
        "Result: " + ", ".join(f"{n} {verdict}" for verdict, n in sorted(counts.items())) + ".",
        "",
        "| Id | Difference | Verdict | What was observed |",
        "|---|---|---|---|",
    ]
    lines += [f"| {r['id']} | {cell(r['title'])} | {r['verdict']} | {cell(r['note'])} |" for r in results]
    lines += [
        "",
        "## Also checked",
        "",
        "Not one of the 14. The research inferred that the two sides agree here; \"confirmed\" means they do.",
        "",
        "| Id | Behaviour | Verdict | What was observed |",
        "|---|---|---|---|",
    ]
    lines += [f"| {r['id']} | {cell(r['title'])} | {r['verdict']} | {cell(r['note'])} |" for r in extras]
    (OUT / "results.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main():
    db.wait_for_server()
    conn = db.connect()
    if db.query(conn, "SELECT 1 FROM sys.databases WHERE name = %s", (SCRATCH_DB,)):
        db.execute(conn, f"ALTER DATABASE [{SCRATCH_DB}] SET SINGLE_USER WITH ROLLBACK IMMEDIATE; DROP DATABASE [{SCRATCH_DB}];")
    db.execute(conn, f"CREATE DATABASE [{SCRATCH_DB}]")
    conn.close()

    spark = start_spark()
    env = environment(spark)
    print("Running the inferred-difference cases", flush=True)
    results = [run_case(case, spark) for case in cases.CASES]
    extras = [run_case(case, spark) for case in cases.EXTRA_CASES]
    spark.stop()

    conn = db.connect()
    db.execute(conn, f"ALTER DATABASE [{SCRATCH_DB}] SET SINGLE_USER WITH ROLLBACK IMMEDIATE; DROP DATABASE [{SCRATCH_DB}];")
    conn.close()

    payload = {"environment": env, "results": results, "also_checked": extras}
    (OUT / "results.json").write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n",
                                      encoding="utf-8", newline="\n")
    write_markdown(env, results, extras)
    not_run = [r["id"] for r in results + extras if r["verdict"] == "not run"]
    if not_run:
        sys.exit(f"Cases that did not run: {', '.join(not_run)}")


if __name__ == "__main__":
    main()
